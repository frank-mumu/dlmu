def style_guide_text():
    """渲染成可读文字，注入 writing_guide 与简报。"""
    lines = ["【小红书爆款风格要求（模仿写法）】"]
    lines.append("目标调性：像上岸学姐/学长朋友聊天——真实、亲切、有温度，像『分享』不是『说教』。")

    lines.append("\n▶ 标题：7 类钩子任选（数字须真实，否则改定性）")
    for p in TITLE_PATTERNS:
        lines.append(f"  · {p['name']}：{p['formula']}")
        lines.append(f"    例：{p['example']}")

    lines.append("\n▶ 开场（首段/首页）：用『你』字句让考生认领『这说的不就是我』")
    for h in OPENING_HOOKS:
        lines.append(f"  · {h['name']}：{h['example']}")

    lines.append("\n▶ 语气 & 排版")
    for r in TONE_RULES:
        lines.append(f"  · {r}")

    lines.append("\n▶ 每页结构：heading(结论式小标题) → lead(你字句引入) → 2-4 要点(结论先行+校事实) → callout(重点/避坑)")
    lines.append(f"  emoji 套件（克制）：{ ' / '.join(f'{k}{v}' for k,v in EMOJI_KIT.items()) }")

    lines.append("\n▶ 结尾互动（选 1，抛具体问题）")
    for c in CTA_TEMPLATES:
        lines.append(f"  · {c}")

    lines.append("\n▶ 必须做")
    for d in DO_LIST:
        lines.append(f"  ✅ {d}")
    lines.append("\n▶ 禁止做")
    for d in DONT_LIST:
        lines.append(f"  ❌ {d}")

    lines.append("\n▶ 正反对照（直接模仿 good）")
    lines.append(f"  差：{BEFORE_AFTER['bad']}")
    lines.append(f"  好：{BEFORE_AFTER['good']}")
    lines.append(f"  差页：{BEFORE_AFTER['bad_page']}")
    lines.append(f"  好页：{BEFORE_AFTER['good_page']}")
    return "\n".join(lines)


